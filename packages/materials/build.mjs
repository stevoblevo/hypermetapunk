// plan C4: reproducible, isolated material snapshot; no production runtime edits.
import { readFileSync, mkdirSync, writeFileSync, existsSync, readdirSync, mkdtempSync, renameSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = p => readFileSync(resolve(root, p), 'utf8');
const version = '0.2.0-materials.1';
const base = 'experiments/materials/project/';
const tokens = JSON.parse(read(base + 'tokens.json'));
const palettes = Object.fromEntries(tokens.color.themes.map(({id}) => [id,
  Object.fromEntries(tokens.color.tokens.map(t => [t.name, t.value[id]]))]));
let material = read(base + 'components/materials.js');
const start = material.indexOf('  function palette(look, el) {');
const end = material.indexOf('  function texture(', start);
if (start < 0 || end < 0) throw Error('Material source changed; review extraction');
material = material.slice(0, start) + `  function palette(look) {
    return Object.fromEntries(Object.entries(PALETTES[look]).map(([key, value]) => [key, rgb(value)]).filter(([, value]) => value));
  }\n` + material.slice(end);
let bundle = `// Generated by packages/materials/build.mjs. Optional candidate ${version}.\nconst VERSION = '${version}';\nconst PALETTES = ${JSON.stringify(palettes)};\nconst H = { theme: { get: () => 'dusk' } };\nconst window = { Hypermetapunk: H };\nconst document = undefined;\n`;
bundle += material + '\n' + read(base + 'components/worlds.js') + '\n';
bundle += read('packages/materials/src/adapter.js');
const dest = resolve(root, 'packages/materials/v', version);
const files = {'materials.mjs': bundle, 'index.d.ts': read('packages/materials/src/index.d.ts')};
files['manifest.json'] = JSON.stringify({version, status:'experimental', renderer:'canvas-2d', files:Object.fromEntries(Object.entries(files).map(([name, text]) => [name, createHash('sha256').update(text).digest('hex')]))}, null, 2) + '\n';

// Validate every byte before any write. An existing version is immutable, even
// when incomplete/corrupt; repairs and source changes require a new version.
if (existsSync(dest)) {
  const names = Object.keys(files).sort();
  if (JSON.stringify(readdirSync(dest).sort()) !== JSON.stringify(names)) {
    throw new Error(`Immutable snapshot ${version} has a different file inventory; use a new version`);
  }
  for (const name of names) {
    if (!readFileSync(resolve(dest, name)).equals(Buffer.from(files[name]))) {
      throw new Error(`Immutable snapshot ${version}/${name} differs; use a new version`);
    }
  }
  console.log(`Verified immutable material snapshot ${version} (no writes)`);
} else {
  mkdirSync(dirname(dest), {recursive:true});
  const staging = mkdtempSync(resolve(dirname(dest), '.material-build-'));
  try {
    for (const [name, text] of Object.entries(files)) writeFileSync(resolve(staging, name), text, {flag:'wx'});
    renameSync(staging, dest);
  } finally {
    rmSync(staging, {recursive:true, force:true});
  }
  console.log(`Created material snapshot ${version}`);
}
